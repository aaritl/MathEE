def create_window(
    length,
    window_type="hann"
):
    """
    Create the window applied before
    calculating the FFT.
    """

    if window_type == "hann":

        return np.hanning(
            length
        )

    elif window_type == "none":

        return np.ones(
            length
        )

    else:

        raise ValueError(
            "window_type must be "
            "'hann' or 'none'"
        )

