@dataclass
class Wave:

    frequency: float
    amplitude: float
    phase: float
    fft_index: int

def get_dominant_waves(
    frequencies,
    amplitudes,
    phases,
    top_n=10,
    min_freq=20,
    max_freq=None
):
    """
    Find the strongest Fourier components
    within the selected frequency range.
    """

    if max_freq is None:

        max_freq = frequencies[-1]

    # Select valid frequencies
    valid = (
        (frequencies >= min_freq)
        & (frequencies <= max_freq)
        & (frequencies > 0)
    )

    valid_indices = (
        np.flatnonzero(valid)
    )

    if len(valid_indices) == 0:

        return []

    # Sort by amplitude
    sorted_indices = valid_indices[
        np.argsort(
            amplitudes[
                valid_indices
            ]
        )[::-1]
    ]

    # Select strongest components
    selected = (
        sorted_indices[:top_n]
    )

    waves = []

    for index in selected:

        waves.append(
            Wave(
                frequency=float(
                    frequencies[index]
                ),

                amplitude=float(
                    amplitudes[index]
                ),

                phase=float(
                    phases[index]
                ),

                fft_index=int(index)
            )
        )

    # Sort by frequency
    waves.sort(
        key=lambda wave:
        wave.frequency
    )

    return waves

