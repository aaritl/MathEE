def compute_fft(
    signal,
    sample_rate,
    window_type="hann"
):
    """
    Calculate the one-sided FFT.

    Returns:
        frequencies
        amplitudes
        phases
        spectrum
    """

    N = len(signal)

    # --------------------------------------------------
    # Apply window
    # --------------------------------------------------

    window = create_window(
        N,
        window_type
    )

    windowed_signal = (
        signal * window
    )

    # --------------------------------------------------
    # Fourier Transform
    # --------------------------------------------------

    spectrum = rfft(
        windowed_signal
    )

    # Frequency corresponding
    # to each FFT bin
    frequencies = rfftfreq(
        N,
        d=1 / sample_rate
    )

    # --------------------------------------------------
    # Calculate amplitudes
    # --------------------------------------------------

    coherent_gain = np.mean(
        window
    )

    amplitudes = (
        np.abs(spectrum)
        / (N * coherent_gain)
    )

    # rFFT contains only positive
    # frequencies, so double the
    # non-DC components.
    if N > 1:

        amplitudes[1:-1] *= 2

    # --------------------------------------------------
    # Calculate phase
    # --------------------------------------------------

    # FFT naturally produces:
    #
    # A cos(2πft + θ)
    #
    # We want:
    #
    # A sin(2πft + φ)
    #
    # Since:
    #
    # cos(x) = sin(x + π/2)
    #
    # φ = θ + π/2

    phases = (
        np.angle(spectrum)
        + np.pi / 2
    )

    # Keep phase between -π and π
    phases = (
        (phases + np.pi)
#         % (2 * np.pi)
        - np.pi
    )

    return (
        frequencies,
        amplitudes,
        phases,
        spectrum
    )

