def save_wav(
    path,
    sample_rate,
    signal
):
    """
    Save a floating-point signal
    as a 16-bit PCM WAV file.
    """

    signal = np.asarray(
        signal,
        dtype=np.float64
    )

    peak = np.max(
        np.abs(signal)
    )

    if peak > 0:

        signal = (
            signal / peak
        )

    signal = np.clip(
        signal,
        -1,
        1
    )

    pcm = np.round(
        signal * 32767
    ).astype(np.int16)

    wavfile.write(
        path,
        sample_rate,
        pcm
    )

