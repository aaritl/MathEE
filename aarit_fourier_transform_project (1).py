def calculate_error(
    original,
    reconstructed
):
    """
    Calculate MSE and RMSE.
    """

    error = (
        original
        - reconstructed
    )

    mse = np.mean(
        error ** 2
    )

    rmse = np.sqrt(
        mse
    )

    return mse, rmse

