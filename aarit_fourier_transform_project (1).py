def reconstruct_from_waves(
    waves,
    num_samples,
    sample_rate
):
    """
    Reconstruct the audio by directly summing
    the extracted sine functions.

    x(t) = Σ Aᵢ sin(2πfᵢt + φᵢ)
    """

    t = (
        np.arange(num_samples)
        / sample_rate
    )

    reconstructed = np.zeros(
        num_samples,
        dtype=np.float64
    )

    for wave in waves:

        reconstructed += (
            wave.amplitude
            * np.sin(
                2 * np.pi
                * wave.frequency
                * t
                + wave.phase
            )
        )

    return t, reconstructed

